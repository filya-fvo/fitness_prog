def validate(programs: list[dict]) -> None:
    names = json.loads((Path(__file__).resolve().parent / "seed_content" / "exercises.json").read_text(encoding="utf-8"))
    known = {e["name_ru"] for e in names}
    canonical_equipment = {"bodyweight", "bands", "dumbbells", "barbell", "machines"}
    missing: set[str] = set()
    invalid: list[str] = []
    shoulder_unsafe = (
        "жим штанги", "жим гантелей", "жим в тренажёре", "жим вверх", "жим арнольда",
        "отжим", "брусь", "подтягив", "верхнего блока", "горизонтального блока",
        "тяга штанги", "тяга гантели", "пуловер", "развод", "развед", "махи",
        "планка", "птица-собака", "фермер", "из-за головы", "француз",
    )
    knee_unsafe = ("присед", "выпад", "разгибания ног", "жим ногами", "прыж", "зашагив")
    spine_unsafe = (
        "станов", "румын", "наклоне", "приседания со штангой",
        "фронтальные приседания", "гудморнинг",
    )
    for p in programs:
        structure = p["structure"]
        schedule = structure["schedule"]
        if len(schedule) != structure["days_per_week"]:
            invalid.append(f"{p['name']}: schedule length differs from days_per_week")
        unknown_equipment = set(structure.get("equipment", [])) - canonical_equipment
        if unknown_equipment:
            invalid.append(f"{p['name']}: unknown equipment {sorted(unknown_equipment)}")
        for d in schedule:
            items = d["exercises"]
            if len(items) not in {6, 7}:
                invalid.append(
                    f"{p['name']} / {d['name']}: expected 6-7 exercises, got {len(items)}"
                )
            exercise_names = [item["exercise_name"] for item in items]
            if len(exercise_names) != len(set(exercise_names)):
                invalid.append(f"{p['name']} / {d['name']}: duplicate exercises")
            for item in items:
                n = item["exercise_name"]
                if n not in known:
                    missing.add(n)
                if "shoulder_sensitive" in structure.get("limitations", []):
                    lowered = n.lower()
                    if any(token in lowered for token in shoulder_unsafe):
                        invalid.append(f"{p['name']} / {d['name']}: shoulder-risk exercise {n}")
                if "no_knee" in structure.get("limitations", []):
                    lowered = n.lower()
                    if any(token in lowered for token in knee_unsafe):
                        invalid.append(f"{p['name']} / {d['name']}: knee-risk exercise {n}")
                if "no_spine" in structure.get("limitations", []):
                    lowered = n.lower()
                    if any(token in lowered for token in spine_unsafe):
                        invalid.append(f"{p['name']} / {d['name']}: spine-risk exercise {n}")

    expected_matrix = {
        (limitation, sex, location, level)
        for limitation in ("no_knee", "no_spine", "shoulder_sensitive")
        for sex in ("male", "female")
        for location in ("gym", "home", "outdoor")
        for level in ("beginner", "intermediate", "advanced")
    }
    actual_matrix = {
        (limitation, structure["sex"][0], structure["location"], structure["level"])
        for p in programs
        for structure in [p["structure"]]
        for limitation in structure.get("limitations", [])
    }
    missing_matrix = expected_matrix - actual_matrix
    if missing_matrix:
        invalid.append(f"limitation matrix gaps: {sorted(missing_matrix)}")
    if missing:
        raise SystemExit("Unknown exercises:\n- " + "\n- ".join(sorted(missing)))
    if invalid:
        raise SystemExit("Invalid programs:\n- " + "\n- ".join(invalid))


def main() -> None:
    programs = build_all()
    validate(programs)
    OUT.write_text(json.dumps(programs, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"wrote {len(programs)} programs -> {OUT}")
    # summary
    from collections import Counter
    c = Counter()
    for p in programs:
        st = p["structure"]
        key = f"{st['sex'][0]}|{st['location']}|{st['level']}|lim={','.join(st['limitations']) or '-'}"
        c[key] += 1
    for k, v in sorted(c.items()):
        print(f"  {k}: {v}")


if __name__ == "__main__":
    main()
